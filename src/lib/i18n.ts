export type ClientKey = keyof (typeof DICT)["en"];

export function t(locale: Locale, key: ClientKey, vars?: Record<string, string | number>): string {
  const table = DICT[locale] as Record<string, string>;
  let value = table[key] ?? (DICT.en as Record<string, string>)[key] ?? String(key);
  if (vars) for (const [k, v] of Object.entries(vars)) value = value.replace(`{${k}}`, String(v));
  return value;
}

export function normaliseLocale(value: string | undefined | null): Locale {
  return value === "fr" ? "fr" : "en";
}

/**
 * Picks the French value when the visitor is browsing in French and a
 * translation has actually been authored; otherwise falls back to English so a
 * missing translation degrades to readable copy rather than a blank field.
 */
export function pick(locale: Locale, en: string | null | undefined, fr: string | null | undefined): string {
  if (locale === "fr" && fr && fr.trim().length > 0) return fr;
  return en ?? "";
}
