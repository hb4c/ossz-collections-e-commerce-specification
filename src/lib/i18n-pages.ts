/** Resolves page copy first, then falls back to the shared client strings. */
export function t(locale: Locale, key: PageKey | ClientKey, vars?: Record<string, string | number>): string {
  const table = PAGES[locale] as Record<string, string>;
  const raw = table[key] ?? (PAGES.en as Record<string, string>)[key];
  if (raw === undefined) return tClient(locale, key as ClientKey, vars);
  let value = raw;
  if (vars) for (const [k, v] of Object.entries(vars)) value = value.replace(`{${k}}`, String(v));
  return value;
}

